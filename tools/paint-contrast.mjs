/**
 * Contrast of the hero's words against the painting they sit on, measured, not guessed.
 *
 * For each viewport it loads the built page, hides the text, photographs the hero, and then
 * reads the pixels under every line of every word of the hero (the headline, the lead, the note,
 * the hint, the wordmark and the navigation). The worst pixel under a line, set against the text
 * colour, is that line's contrast; WCAG asks for 4.5:1. With JS on this measures the live canvas at its
 * first frame, which is the still; with JS off, the still itself.
 *
 *   node tools/paint-contrast.mjs [--sizes 390x844,1440x900] [--js off] [--min 4.5] [--page]
 *
 * --page also checks every line of text on the whole page (hidden, photographed full length at
 * 1x, read pixel by pixel) at 390, 768, 1440 and 2560 wide, and the numbers in the step markers.
 * Those are generated by CSS (a text box taller than the pad they sit in would read the snow around
 * it), so each is measured on its ink: the middle of its box, against white.
 *
 * It runs against dist/ (run `npm run build` first) and exits 1 if any line falls short. The
 * page's own CSP refuses the style that hides the words, so the context bypasses CSP; nothing
 * else here depends on that.
 */
import http from 'node:http';
import { readFile, stat } from 'node:fs/promises';
import path from 'node:path';
import { chromium } from 'playwright-core';
import sharp from 'sharp';

const args = process.argv.slice(2);
const opt = (k, d) => { const i = args.indexOf('--' + k); return i >= 0 ? args[i + 1] : d; };
const SIZES = opt('sizes', '320x568,360x640,390x844,412x915,768x1024,820x1180,844x390,1024x768,1280x720,1366x768,1440x900,1536x864,1920x1080,2560x1440@1.5,3440x1440').split(',');
const JS = opt('js', 'on') !== 'off';
const MIN = +opt('min', '4.5');

const ROOT = path.resolve('dist');
const MIME = { '.html': 'text/html; charset=utf-8', '.css': 'text/css', '.js': 'text/javascript', '.png': 'image/png', '.webp': 'image/webp', '.woff2': 'font/woff2' };
const server = http.createServer(async (req, res) => {
  let f = path.join(ROOT, decodeURIComponent(new URL(req.url, 'http://x').pathname));
  let s = await stat(f).catch(() => null);
  if (s?.isDirectory()) { f = path.join(f, 'index.html'); s = await stat(f).catch(() => null); }
  if (!s) { res.writeHead(404).end(); return; }
  res.writeHead(200, { 'Content-Type': MIME[path.extname(f)] || 'application/octet-stream', 'Cache-Control': 'no-store' });
  res.end(await readFile(f));
});
await new Promise((r) => server.listen(0, '127.0.0.1', r));
const origin = `http://127.0.0.1:${server.address().port}`;

const lin = (c) => { c /= 255; return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4; };
const lum = (r, g, b) => 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b);
const parse = (css) => (css.match(/[\d.]+/g) || [0, 0, 0]).slice(0, 3).map(Number);

let failed = 0;
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  for (const spec of SIZES) {
    const m = /^(\d+)x(\d+)(?:@([\d.]+))?$/.exec(spec.trim());
    const w = +m[1], h = +m[2], dpr = m[3] ? +m[3] : 1;
    const ctx = await browser.newContext({ viewport: { width: w, height: h }, deviceScaleFactor: dpr, javaScriptEnabled: JS, isMobile: w < 768, hasTouch: w < 768, locale: 'lt-LT', bypassCSP: true });
    const page = await ctx.newPage();
    await page.goto(origin + '/', { waitUntil: 'load' });
    await page.waitForTimeout(JS ? 1600 : 600);
    // collect the line boxes and colours, then hide the words
    const lines = await page.evaluate(() => {
      const sel = ['.hero h1', '.hero__lead', '.hero__note', '.hero__hint', '.head .mark span', '.head .nav a'];
      const out = [];
      for (const s of sel) for (const el of document.querySelectorAll(s)) {
        if (!el.getClientRects().length) continue;
        const cs = getComputedStyle(el);
        if (cs.visibility === 'hidden' || +cs.opacity === 0) continue;
        const r = document.createRange();
        r.selectNodeContents(el);
        for (const q of r.getClientRects()) if (q.width > 1 && q.height > 1 && q.top < innerHeight && q.bottom > 0) out.push({ sel: s, color: cs.color, x: q.left, y: q.top, w: q.width, h: q.height });
      }
      const st = document.createElement('style');
      st.textContent = '.hero h1,.hero__lead,.hero__note,.hero__hint,.head .mark span,.head .nav a{color:transparent!important;text-shadow:none!important}.hero__hint{opacity:1!important}';
      document.head.appendChild(st);
      return out;
    });
    await page.waitForTimeout(250);
    const png = await page.screenshot({ type: 'png' });
    const { data, info } = await sharp(png).removeAlpha().raw().toBuffer({ resolveWithObject: true });
    let worst = Infinity, worstAt = null, count = 0;
    for (const ln of lines) {
      const ink = lum(...parse(ln.color));
      const x0 = Math.max(0, Math.floor(ln.x * dpr)), x1 = Math.min(info.width, Math.ceil((ln.x + ln.w) * dpr));
      const y0 = Math.max(0, Math.floor(ln.y * dpr)), y1 = Math.min(info.height, Math.ceil((ln.y + ln.h) * dpr));
      let minL = Infinity, maxL = 0;
      for (let y = y0; y < y1; y++) for (let x = x0; x < x1; x++) {
        const i = (y * info.width + x) * 3;
        const L = lum(data[i], data[i + 1], data[i + 2]);
        if (L < minL) minL = L;
        if (L > maxL) maxL = L;
      }
      // ink darker than the ground: the darkest ground pixel is the worst case
      const c = ink < 0.5 ? (minL + 0.05) / (ink + 0.05) : (ink + 0.05) / (maxL + 0.05);
      count++;
      if (c < worst) { worst = c; worstAt = ln; }
      if (c < MIN) { failed++; console.log(`  FAIL ${spec} ${ln.sel} at (${Math.round(ln.x)},${Math.round(ln.y)}) ${Math.round(ln.w)}x${Math.round(ln.h)}: ${c.toFixed(2)}:1`); }
    }
    console.log(`${worst >= MIN ? 'ok  ' : 'FAIL'} ${spec.padEnd(14)} ${count} lines, worst ${worst.toFixed(2)}:1${worstAt ? ' (' + worstAt.sel + ')' : ''}`);
    await ctx.close();
  }

  /* --page: every line of text on the whole page, against whatever is behind it (solid colour,
     gradient, painting). The words are hidden, the page photographed full length at 1x, and the
     pixels under each line read. This is the check that finds ink on a vista's fade, or a link
     colour on a tinted panel, which a look at the computed colours would miss. */
  if (args.includes('--page')) {
    for (const spec of opt('page-sizes', '390x844,768x1024,1440x900,2560x1440').split(',')) {
      const [w, h] = spec.split('x').map(Number);
      const ctx = await browser.newContext({ viewport: { width: w, height: h }, deviceScaleFactor: 1, javaScriptEnabled: JS, isMobile: w < 768, hasTouch: w < 768, locale: 'lt-LT', bypassCSP: true });
      const page = await ctx.newPage();
      await page.goto(origin + '/', { waitUntil: 'load' });
      await page.waitForTimeout(JS ? 1600 : 600);
      if (JS) {
        await page.evaluate(async () => { for (let y = 0; y < document.documentElement.scrollHeight; y += innerHeight * 0.8) { scrollTo(0, y); await new Promise((r) => setTimeout(r, 90)); } scrollTo(0, 0); });
        await page.waitForTimeout(600);
      }
      const lines = await page.evaluate(() => {
        const out = [];
        const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
        let n;
        while ((n = walker.nextNode())) {
          if (!n.textContent.trim()) continue;
          const el = n.parentElement;
          if (el.closest('script,style,noscript,.sr')) continue;
          const det = el.closest('details');
          if (det && !det.open && !el.closest('summary')) continue;
          const cs = getComputedStyle(el);
          if (cs.display === 'none' || cs.visibility === 'hidden') continue;
          let op = 1;
          for (let e = el; e; e = e.parentElement) op *= +getComputedStyle(e).opacity;
          if (op < 0.5) continue;
          const r = document.createRange();
          r.selectNodeContents(n);
          for (const q of r.getClientRects()) if (q.width > 1 && q.height > 1) out.push({ text: n.textContent.trim().slice(0, 30), cls: el.className || el.tagName, color: cs.color, x: q.left + scrollX, y: q.top + scrollY, w: q.width, h: q.height });
        }
        for (const el of document.querySelectorAll('.step__n')) {
          const b = el.getBoundingClientRect();
          if (b.width > 1) out.push({ text: 'step ' + getComputedStyle(el, '::after').content, cls: 'step__n', color: 'white', x: b.left + scrollX, y: b.top + scrollY, w: b.width, h: b.height, digit: true });
        }
        const st = document.createElement('style');
        st.textContent = '*,*::after{color:transparent!important;-webkit-text-fill-color:transparent!important;text-decoration-color:transparent!important;text-shadow:none!important}.hero__hint{opacity:1!important}';
        document.head.appendChild(st);
        return out;
      });
      await page.waitForTimeout(300);
      const { data, info } = await sharp(await page.screenshot({ type: 'png', fullPage: true })).removeAlpha().raw().toBuffer({ resolveWithObject: true });
      const results = [];
      for (const ln of lines) {
        const ink = ln.color === 'white' ? 1 : lum(...parse(ln.color));
        let minL = Infinity, maxL = 0;
        // a digit's box is taller than its ink: its middle (a fifth in from each side, a quarter from top and foot) is the ink
        const px = ln.digit ? ln.w * 0.2 : 0, py = ln.digit ? ln.h * 0.25 : 0;
        const x0 = Math.max(0, Math.floor(ln.x + px)), x1 = Math.min(info.width, Math.ceil(ln.x + ln.w - px));
        const y0 = Math.max(0, Math.floor(ln.y + py)), y1 = Math.min(info.height, Math.ceil(ln.y + ln.h - py));
        for (let y = y0; y < y1; y++) for (let x = x0; x < x1; x++) {
          const k = (y * info.width + x) * 3;
          const L = lum(data[k], data[k + 1], data[k + 2]);
          if (L < minL) minL = L;
          if (L > maxL) maxL = L;
        }
        if (minL === Infinity) continue;
        results.push({ ...ln, c: ink < 0.5 ? (minL + 0.05) / (ink + 0.05) : (ink + 0.05) / (maxL + 0.05) });
      }
      results.sort((a, b) => a.c - b.c);
      const bad = results.filter((r) => r.c < MIN);
      failed += bad.length;
      for (const b of bad.slice(0, 8)) console.log(`  FAIL ${spec} page y=${Math.round(b.y)} .${String(b.cls).split(' ')[0]} "${b.text}": ${b.c.toFixed(2)}:1`);
      console.log(`${bad.length ? 'FAIL' : 'ok  '} ${spec.padEnd(11)} whole page: ${results.length} lines, worst ${results[0] ? results[0].c.toFixed(2) : 'n/a'}:1${results[0] ? ' (.' + String(results[0].cls).split(' ')[0] + ')' : ''}`);
      const digits = results.filter((r) => r.digit);
      console.log(`     the ${digits.length} step numbers, on their ink: worst ${digits.length ? digits[0].c.toFixed(2) : 'n/a'}:1`);
      await ctx.close();
    }
  }
} finally {
  await browser.close();
  server.close();
}
process.exit(failed ? 1 : 0);
